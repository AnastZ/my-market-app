-- Таблица товаров
CREATE TABLE IF NOT EXISTS ITEM (
                                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    TITLE VARCHAR(255) NOT NULL,
    DESCRIPTION TEXT,
    IMG_PATH VARCHAR(500),
    PRICE BIGINT NOT NULL,
    VERSION BIGINT DEFAULT 0
    );

-- Таблица корзин
CREATE TABLE IF NOT EXISTS CART (
                                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    USERNAME VARCHAR(255) NOT NULL UNIQUE,
    VERSION BIGINT DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );

-- Таблица товаров в корзине
CREATE TABLE IF NOT EXISTS CART_ITEM (
                                         ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         CART_ID BIGINT NOT NULL,
                                         ITEM_ID BIGINT NOT NULL,
                                         TITLE VARCHAR(255) NOT NULL,
    COUNT BIGINT DEFAULT 0,
    ONE_ITEM_PRICE BIGINT NOT NULL,
    VERSION BIGINT DEFAULT 0,
    FOREIGN KEY (CART_ID) REFERENCES CART(ID) ON DELETE CASCADE,
    FOREIGN KEY (ITEM_ID) REFERENCES ITEM(ID) ON DELETE CASCADE,
    CONSTRAINT UNIQUE_CART_ITEM UNIQUE (CART_ID, ITEM_ID)
    );

-- Таблица заказов
CREATE TABLE IF NOT EXISTS ORDER_TABLE (
                                           ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           VERSION BIGINT DEFAULT 0,
                                           CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Таблица товаров в заказе (с добавленным полем TITLE)
CREATE TABLE IF NOT EXISTS ORDER_ITEM (
                                          ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          ORDER_ID BIGINT NOT NULL,
                                          ITEM_ID BIGINT NOT NULL,
                                          TITLE VARCHAR(255) NOT NULL,  -- ДОБАВЛЕНО: название товара на момент заказа
    COUNT BIGINT DEFAULT 0,
    PRICE_AT_ORDER BIGINT NOT NULL,
    VERSION BIGINT DEFAULT 0,
    FOREIGN KEY (ORDER_ID) REFERENCES ORDER_TABLE(ID) ON DELETE CASCADE,
    FOREIGN KEY (ITEM_ID) REFERENCES ITEM(ID) ON DELETE CASCADE,
    CONSTRAINT UNIQUE_ORDER_ITEM UNIQUE (ORDER_ID, ITEM_ID)
    );

-- Индексы для оптимизации запросов
CREATE INDEX IF NOT EXISTS IDX_CART_USERNAME ON CART(USERNAME);
CREATE INDEX IF NOT EXISTS IDX_CART_ITEM_CART_ID ON CART_ITEM(CART_ID);
CREATE INDEX IF NOT EXISTS IDX_CART_ITEM_ITEM_ID ON CART_ITEM(ITEM_ID);
CREATE INDEX IF NOT EXISTS IDX_ORDER_ITEM_ORDER_ID ON ORDER_ITEM(ORDER_ID);
CREATE INDEX IF NOT EXISTS IDX_ORDER_ITEM_ITEM_ID ON ORDER_ITEM(ITEM_ID);
CREATE INDEX IF NOT EXISTS IDX_CART_ITEM_COMPOSITE ON CART_ITEM(CART_ID, ITEM_ID);
CREATE INDEX IF NOT EXISTS IDX_ITEM_PRICE ON ITEM(PRICE);